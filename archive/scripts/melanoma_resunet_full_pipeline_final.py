"""## 25. Lesion ROI Generation

The main segmentation comparison used raw masks thresholded at 0.5. ROI extraction also starts from the 0.5 mask. Optional largest-component/hole-filling logic is controlled by `ROI_POSTPROCESS` and affects only ROI generation, never the reported team-comparison segmentation metrics.
"""

def prepare_mask_for_roi(probability_mask, threshold=SEG_THRESHOLD):
    binary = np.asarray(probability_mask, dtype=np.float32) >= float(threshold)
    if ROI_POSTPROCESS and np.any(binary):
        labels, count = ndimage.label(binary)
        if count > 1:
            sizes = ndimage.sum(binary, labels, index=np.arange(1, count + 1))
            binary = labels == (int(np.argmax(sizes)) + 1)
        binary = ndimage.binary_fill_holes(binary)
    return binary.astype(np.uint8)


def extract_lesion_roi(image, predicted_mask, padding_fraction=ROI_PADDING_FRACTION):
    image_array = np.asarray(image.convert("RGB") if isinstance(image, Image.Image) else image)
    if image_array.ndim != 3 or image_array.shape[-1] != 3:
        raise ValueError("image must have RGB shape H×W×3")
    mask = np.asarray(predicted_mask).squeeze().astype(bool)
    height, width = image_array.shape[:2]
    if mask.shape != (height, width):
        mask = np.asarray(
            Image.fromarray(mask.astype(np.uint8) * 255).resize((width, height), Image.Resampling.NEAREST)
        ) > 127

    mask_fraction = float(mask.mean())
    if not np.any(mask):
        return image_array.copy(), (0, 0, width, height), True, "empty_mask"
    if mask_fraction < MIN_VALID_MASK_FRACTION:
        return image_array.copy(), (0, 0, width, height), True, "mask_too_small"
    if mask_fraction > MAX_VALID_MASK_FRACTION:
        return image_array.copy(), (0, 0, width, height), True, "mask_too_large"

    y_coordinates, x_coordinates = np.where(mask)
    x0, x1 = int(x_coordinates.min()), int(x_coordinates.max()) + 1
    y0, y1 = int(y_coordinates.min()), int(y_coordinates.max()) + 1
    padding_x = max(1, int(round((x1 - x0) * padding_fraction)))
    padding_y = max(1, int(round((y1 - y0) * padding_fraction)))
    x0, x1 = max(0, x0 - padding_x), min(width, x1 + padding_x)
    y0, y1 = max(0, y0 - padding_y), min(height, y1 + padding_y)
    if x1 <= x0 or y1 <= y0:
        return image_array.copy(), (0, 0, width, height), True, "invalid_bounding_box"
    if (x1 - x0) < MIN_ROI_SIDE_PIXELS or (y1 - y0) < MIN_ROI_SIDE_PIXELS:
        return image_array.copy(), (0, 0, width, height), True, "crop_too_small"
    return image_array[y0:y1, x0:x1].copy(), (x0, y0, x1, y1), False, None


