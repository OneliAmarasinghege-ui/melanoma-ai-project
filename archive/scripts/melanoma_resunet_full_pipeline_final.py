def generate_roi_manifest(frame, segmenter, checkpoint_path):
    frame = frame.copy().reset_index(drop=True)
    checkpoint_path = Path(checkpoint_path)
    completed = {}
    if checkpoint_path.exists():
        previous = pd.read_csv(checkpoint_path)
        for row in previous.to_dict("records"):
            if row.get("roi_path") and Path(str(row["roi_path"])).exists():
                completed[str(row["image_name"])] = row

    pending = frame.loc[~frame.image_name.astype(str).isin(completed)].copy()
    pending_lookup = pending.set_index("original_path").to_dict(orient="index")
    print(f"ROI generation: {len(completed)} reusable; {len(pending)} pending.")
    new_records = []
    inference_dataset = make_segmentation_inference_dataset(pending.original_path.astype(str).tolist())
    processed = 0

    for path_batch, image_batch in tqdm(inference_dataset, desc="ResUNet ROI generation"):
        predicted_probabilities = segmenter.predict_on_batch(image_batch).astype(np.float32)[..., 0]
        for encoded_path, small_probability in zip(path_batch.numpy(), predicted_probabilities):
            original_path = encoded_path.decode("utf-8")
            source_row = pending_lookup[original_path]
            original = load_rgb_pil(original_path)
            probability_at_original_size = np.asarray(
                Image.fromarray(small_probability.astype(np.float32), mode="F").resize(
                    original.size, Image.Resampling.BILINEAR
                ), dtype=np.float32
            )
            binary_mask = prepare_mask_for_roi(probability_at_original_size)
            roi, bounding_box, fallback_used, fallback_reason = extract_lesion_roi(original, binary_mask)
            roi_path = ROI_DIR / f"{source_row['image_name']}.jpg"
            Image.fromarray(roi).save(roi_path, format="JPEG", quality=95, optimize=True)
            record = dict(source_row)
            record.update({
                "original_path": original_path,
                "roi_path": str(roi_path),
                "bbox": json.dumps([int(value) for value in bounding_box]),
                "roi_fallback_used": bool(fallback_used),
                "roi_fallback_reason": fallback_reason,
            })
            new_records.append(record)
        processed += len(path_batch)
        if processed % 500 < SEG_BATCH_SIZE:
            pd.DataFrame(list(completed.values()) + new_records).to_csv(checkpoint_path, index=False)

    result = pd.DataFrame(list(completed.values()) + new_records)
    if len(result) != len(frame) or result.image_name.nunique() != len(frame):
        raise RuntimeError("ROI manifest is incomplete or contains duplicate image IDs.")
    if not result.roi_path.map(lambda value: Path(value).exists()).all():
        raise RuntimeError("At least one generated ROI path is missing.")
    result = frame[["image_name"]].merge(result, on="image_name", validate="one_to_one")
    result.to_csv(checkpoint_path, index=False)
    return result


