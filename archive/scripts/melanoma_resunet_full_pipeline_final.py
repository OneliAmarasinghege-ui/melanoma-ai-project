def load_rgb_pil(path):
    with Image.open(path) as image:
        return image.convert("RGB").copy()


def load_mask_pil(path):
    with Image.open(path) as mask:
        return mask.convert("L").copy()


def validate_segmentation_files(frame):
    failures = []
    for row in tqdm(frame.itertuples(index=False), total=len(frame), desc="Checking ISIC image-mask files"):
        try:
            image = load_rgb_pil(row.image_path)
            mask = load_mask_pil(row.mask_path)
            if image.size != mask.size:
                failures.append({"image_id": row.image_id, "problem": f"dimension mismatch {image.size} vs {mask.size}"})
            mask_values = np.asarray(mask)
            if mask_values.size == 0:
                failures.append({"image_id": row.image_id, "problem": "empty mask file"})
        except Exception as exc:
            failures.append({"image_id": row.image_id, "problem": repr(exc)})
    return pd.DataFrame(failures, columns=["image_id", "problem"])


