def zip_uncompressed_size(zip_path):
    with zipfile.ZipFile(zip_path) as archive:
        return sum(info.file_size for info in archive.infolist())


def available_bytes(path):
    return shutil.disk_usage(Path(path)).free


def safe_extract_zip(
    zip_path,
    destination,
    marker_name=".extraction_complete",
):
    zip_path = Path(zip_path)
    destination = Path(destination)
    marker = destination / marker_name

    if marker.exists():
        print("Extraction marker found; skipping:", destination)
        return destination

    required = int(zip_uncompressed_size(zip_path) * 1.15)
    free = available_bytes(destination.parent)

    print(
        f"{zip_path.name}: approximately "
        f"{required / 1e9:.1f} GB extraction space required; "
        f"{free / 1e9:.1f} GB currently free."
    )

    if free < required:
        raise RuntimeError(
            f"Not enough temporary Colab disk space to extract "
            f"{zip_path.name}. Need roughly "
            f"{(required - free) / 1e9:.1f} GB more free space."
        )

    destination.mkdir(parents=True, exist_ok=True)
    root = destination.resolve()

    with zipfile.ZipFile(zip_path) as archive:
        for member in tqdm(
            archive.infolist(),
            desc=f"Extracting {zip_path.name}",
        ):
            target = (destination / member.filename).resolve()

            if root not in target.parents and target != root:
                raise RuntimeError(
                    f"Unsafe ZIP member path: {member.filename}"
                )

            archive.extract(member, destination)

    marker.write_text(
        f"Extracted from {zip_path.name}\n",
        encoding="utf-8",
    )

    return destination


def download_extract_and_cleanup(
    dataset_key,
    destination,
):
    """
    Download and extract one large ZIP only when its extracted
    dataset is not already available in the current runtime.
    """
    destination = Path(destination)

    if runtime_extraction_complete(destination):
        print(
            f"{dataset_key}: extracted data already exists in "
            f"the current runtime; no download required."
        )
        return None

    archive_path = download_with_resume(
        DATASET_SPECS[dataset_key],
        destination_dir=ARCHIVE_DIR,
    )

    safe_extract_zip(
        archive_path,
        destination,
    )

    if (
        DELETE_RUNTIME_ARCHIVES
        and Path(archive_path).exists()
    ):
        Path(archive_path).unlink()
        print(
            "Deleted temporary ZIP after successful extraction:",
            Path(archive_path).name,
        )

    return archive_path




