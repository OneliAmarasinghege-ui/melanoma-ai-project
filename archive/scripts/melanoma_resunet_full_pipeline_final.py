"""## 10. Paired Augmentation

"""

def _projective_transform(image, transform, interpolation, fill_mode, fill_value=0.0):
    transformed = tf.raw_ops.ImageProjectiveTransformV3(
        images=image[None, ...],
        transforms=transform[None, ...],
        output_shape=tf.cast(tf.shape(image)[:2], tf.int32),
        interpolation=interpolation,
        fill_mode=fill_mode,
        fill_value=tf.cast(fill_value, tf.float32),
    )
    return transformed[0]


def stateless_paired_augmentation(index, pair):
    image, mask = pair
    base_seed = tf.stack([tf.cast(SEED, tf.int32), tf.cast(index % 2147483647, tf.int32)])
    seeds = tf.random.experimental.stateless_split(base_seed, 9)

    horizontal = tf.random.stateless_uniform([], seeds[0]) > 0.5
    vertical = tf.random.stateless_uniform([], seeds[1]) > 0.5
    image = tf.cond(horizontal, lambda: tf.image.flip_left_right(image), lambda: image)
    mask = tf.cond(horizontal, lambda: tf.image.flip_left_right(mask), lambda: mask)
    image = tf.cond(vertical, lambda: tf.image.flip_up_down(image), lambda: image)
    mask = tf.cond(vertical, lambda: tf.image.flip_up_down(mask), lambda: mask)

    angle = tf.random.stateless_uniform([], seeds[2], -10.0, 10.0) * (math.pi / 180.0)
    zoom = tf.random.stateless_uniform([], seeds[3], 0.92, 1.08)
    tx = tf.random.stateless_uniform([], seeds[4], -0.05, 0.05) * float(SEG_IMAGE_SIZE[1])
    ty = tf.random.stateless_uniform([], seeds[5], -0.05, 0.05) * float(SEG_IMAGE_SIZE[0])

    height, width = map(float, SEG_IMAGE_SIZE)
    cx, cy = (width - 1.0) / 2.0, (height - 1.0) / 2.0
    cos_a, sin_a = tf.cos(angle) / zoom, tf.sin(angle) / zoom
    a0, a1 = cos_a, sin_a
    b0, b1 = -sin_a, cos_a
    a2 = cx - a0 * (cx + tx) - a1 * (cy + ty)
    b2 = cy - b0 * (cx + tx) - b1 * (cy + ty)
    transform = tf.stack([a0, a1, a2, b0, b1, b2, 0.0, 0.0])

    image = _projective_transform(image, transform, "BILINEAR", "REFLECT")
    mask = _projective_transform(mask, transform, "NEAREST", "CONSTANT", 0.0)
    image = tf.image.stateless_random_brightness(image, max_delta=0.06, seed=seeds[6])
    image = tf.image.stateless_random_contrast(image, lower=0.90, upper=1.10, seed=seeds[7])
    image = tf.clip_by_value(image, 0.0, 1.0)
    mask = tf.cast(mask >= 0.5, tf.float32)
    return image, mask


