def unfreeze_efficientnet_top(model, last_n=CLS_FINE_TUNE_LAST_N):
    backbone = model.get_layer("efficientnetb0")
    backbone.trainable = True
    cutoff = max(0, len(backbone.layers) - int(last_n))
    for layer_index, layer in enumerate(backbone.layers):
        layer.trainable = layer_index >= cutoff and not isinstance(layer, layers.BatchNormalization)
    print("Trainable upper backbone layers:", sum(layer.trainable for layer in backbone.layers))
    print("All BatchNormalization layers remain frozen:", all(
        not layer.trainable for layer in backbone.layers if isinstance(layer, layers.BatchNormalization)
    ))
    return model


