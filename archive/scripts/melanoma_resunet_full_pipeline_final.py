"""## 37. Grad-CAM

Grad-CAM identifies spatial areas in the lesion ROI that strongly influenced the selected network score. It does **not** demonstrate clinical causality, prove that highlighted structures are diagnostic, or replace expert interpretation.
"""

def get_efficientnet_backbone(classifier):
    for layer in classifier.layers:
        if isinstance(layer, keras.Model) and "efficientnet" in layer.name.lower():
            return layer
    raise ValueError("EfficientNet backbone was not found inside the classifier.")


def find_last_spatial_layer(backbone):
    for layer in reversed(backbone.layers):
        try:
            if len(tuple(layer.output.shape)) == 4:
                return layer
        except Exception:
            continue
    raise ValueError("No four-dimensional spatial layer was found.")


def make_gradcam_heatmap(classifier, image_batch, target_class=1):
    backbone = get_efficientnet_backbone(classifier)
    last_spatial_layer = find_last_spatial_layer(backbone)
    feature_model = keras.Model(backbone.input, last_spatial_layer.output)
    image_batch = tf.cast(image_batch, tf.float32)
    with tf.GradientTape() as tape:
        feature_maps = feature_model(image_batch, training=False)
        tape.watch(feature_maps)
        pooled = classifier.get_layer("classification_gap")(feature_maps)
        dropped = classifier.get_layer("classification_dropout")(pooled, training=False)
        malignant_probability = classifier.get_layer("malignancy_probability")(dropped)[:, 0]
        target_score = malignant_probability if int(target_class) == 1 else 1.0 - malignant_probability
    gradients = tape.gradient(target_score, feature_maps)
    if gradients is None:
        raise RuntimeError("Grad-CAM gradients could not be calculated.")
    weights = tf.reduce_mean(gradients, axis=(1, 2), keepdims=True)
    heatmap = tf.nn.relu(tf.reduce_sum(weights * feature_maps, axis=-1))[0]
    heatmap = heatmap / tf.maximum(tf.reduce_max(heatmap), EPSILON)
    return heatmap.numpy().astype(np.float32), last_spatial_layer.name


def heatmap_overlay(image, heatmap, alpha=0.40):
    image_array = np.asarray(image.convert("RGB") if isinstance(image, Image.Image) else image).astype(np.uint8)
    resized_heatmap = np.asarray(
        Image.fromarray(np.asarray(heatmap, dtype=np.float32), mode="F").resize(
            (image_array.shape[1], image_array.shape[0]), Image.Resampling.BILINEAR
        ), dtype=np.float32
    )
    coloured = (plt.get_cmap("jet")(np.clip(resized_heatmap, 0.0, 1.0))[..., :3] * 255).astype(np.uint8)
    return np.clip((1.0 - alpha) * image_array + alpha * coloured, 0, 255).astype(np.uint8)


def segmentation_overlay(image, binary_mask, alpha=0.35):
    image_array = np.asarray(image.convert("RGB") if isinstance(image, Image.Image) else image).astype(np.uint8)
    mask = np.asarray(binary_mask).squeeze().astype(bool)
    if mask.shape != image_array.shape[:2]:
        mask = np.asarray(
            Image.fromarray(mask.astype(np.uint8) * 255).resize(
                (image_array.shape[1], image_array.shape[0]), Image.Resampling.NEAREST
            )
        ) > 127
    red = np.zeros_like(image_array)
    red[..., 0] = 255
    return np.where(mask[..., None], np.clip((1 - alpha) * image_array + alpha * red, 0, 255), image_array).astype(np.uint8)


