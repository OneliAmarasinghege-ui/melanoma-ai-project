"""## 12. Residual Block

A residual block has a two-convolution learning path and a shortcut path. If the input channel count differs from the requested filters, a 1×1 convolution plus batch normalisation projects the shortcut to the correct shape before addition. No broadcasting is used.
"""

def residual_block(x, filters, name):
    shortcut = x
    residual = layers.Conv2D(filters, 3, padding="same", use_bias=False, name=f"{name}_conv1")(x)
    residual = layers.BatchNormalization(name=f"{name}_bn1")(residual)
    residual = layers.Activation("relu", name=f"{name}_relu1")(residual)
    residual = layers.Conv2D(filters, 3, padding="same", use_bias=False, name=f"{name}_conv2")(residual)
    residual = layers.BatchNormalization(name=f"{name}_bn2")(residual)

    input_channels = shortcut.shape[-1]
    if input_channels != filters:
        shortcut = layers.Conv2D(filters, 1, padding="same", use_bias=False, name=f"{name}_shortcut_conv")(shortcut)
        shortcut = layers.BatchNormalization(name=f"{name}_shortcut_bn")(shortcut)

    output = layers.Add(name=f"{name}_add")([residual, shortcut])
    return layers.Activation("relu", name=f"{name}_out_relu")(output)

"""## 13. ResUNet Architecture

Standard U-Net uses ordinary convolution blocks. **ResUNet** replaces them with residual blocks, allowing information and gradients to travel through shortcut paths. This may improve gradient flow, reduce degradation in deeper networks, preserve useful lower-level features and support lesion-boundary learning. These are motivations, not a claim that ResUNet is already superior. Its validation and held-out test results must be compared experimentally with the team's separate Standard U-Net, Attention U-Net and U-Net++ branches under the same conditions.
"""

def build_resunet(input_shape=(*SEG_IMAGE_SIZE, 3)):
    inputs = keras.Input(shape=input_shape, name="dermoscopic_image")

    encoder_1 = residual_block(inputs, 32, "encoder_1")
    pooled_1 = layers.MaxPooling2D(2, name="pool_1")(encoder_1)
    encoder_2 = residual_block(pooled_1, 64, "encoder_2")
    pooled_2 = layers.MaxPooling2D(2, name="pool_2")(encoder_2)
    encoder_3 = residual_block(pooled_2, 128, "encoder_3")
    pooled_3 = layers.MaxPooling2D(2, name="pool_3")(encoder_3)
    encoder_4 = residual_block(pooled_3, 256, "encoder_4")
    pooled_4 = layers.MaxPooling2D(2, name="pool_4")(encoder_4)

    bottleneck = residual_block(pooled_4, 512, "bottleneck")

    def decoder_block(x, skip, filters, name):
        x = layers.Conv2DTranspose(filters, 2, strides=2, padding="same", name=f"{name}_upsample")(x)
        x = layers.Concatenate(name=f"{name}_skip_concat")([x, skip])
        return residual_block(x, filters, name)

    decoder_4 = decoder_block(bottleneck, encoder_4, 256, "decoder_4")
    decoder_3 = decoder_block(decoder_4, encoder_3, 128, "decoder_3")
    decoder_2 = decoder_block(decoder_3, encoder_2, 64, "decoder_2")
    decoder_1 = decoder_block(decoder_2, encoder_1, 32, "decoder_1")

    outputs = layers.Conv2D(
        filters=1,
        kernel_size=1,
        activation="sigmoid",
        dtype="float32",
        name="lesion_probability",
    )(decoder_1)
    return keras.Model(inputs, outputs, name="ResUNet")

