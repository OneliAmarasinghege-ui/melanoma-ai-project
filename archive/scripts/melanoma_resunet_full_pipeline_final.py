def choose_best_group_holdout(frame, desired_fraction, n_splits, seed):
    splitter = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=seed)
    overall_prevalence = frame.target.mean()
    candidates = []
    for fold_number, (keep_indices, holdout_indices) in enumerate(
        splitter.split(frame, frame.target, groups=frame.patient_id)
    ):
        holdout = frame.iloc[holdout_indices]
        fraction_error = abs(len(holdout) / len(frame) - desired_fraction)
        prevalence_error = abs(holdout.target.mean() - overall_prevalence)
        candidates.append((fraction_error + prevalence_error, fold_number, keep_indices, holdout_indices))
    _, selected_fold, keep_indices, holdout_indices = min(candidates, key=lambda item: (item[0], item[1]))
    print(f"Selected fold {selected_fold} of {n_splits} for desired fraction {desired_fraction:.3f}.")
    return keep_indices, holdout_indices


