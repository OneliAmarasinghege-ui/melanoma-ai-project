def validate_notebook_python_cells(notebook_path):
    notebook_path = Path(notebook_path)
    notebook = json.loads(notebook_path.read_text(encoding="utf-8"))
    failures = []
    for cell_index, cell in enumerate(notebook.get("cells", []), start=1):
        if cell.get("cell_type") != "code":
            continue
        source = "".join(cell.get("source", []))
        try:
            compile(source, f"cell_{cell_index}", "exec", flags=ast.PyCF_ONLY_AST)
        except SyntaxError as exc:
            failures.append({"cell": cell_index, "error": str(exc)})
    if failures:
        raise SyntaxError(f"Notebook AST validation failures: {failures}")
    return len([cell for cell in notebook.get("cells", []) if cell.get("cell_type") == "code"])


