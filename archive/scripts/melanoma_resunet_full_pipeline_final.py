def evaluate_segmenter_streaming(model, dataset, threshold=SEG_THRESHOLD):
    dice_values, iou_values = [], []
    tp = tn = fp = fn = 0
    for images, true_masks in tqdm(dataset, desc="Evaluating ResUNet", leave=False):
        probabilities = model.predict_on_batch(images).astype(np.float32)
        predicted = probabilities >= threshold
        truth = true_masks.numpy() >= 0.5
        axes = (1, 2, 3)
        intersection = np.sum(predicted & truth, axis=axes)
        predicted_sum = np.sum(predicted, axis=axes)
        truth_sum = np.sum(truth, axis=axes)
        union = np.sum(predicted | truth, axis=axes)
        dice_values.extend(((2 * intersection + EPSILON) / (predicted_sum + truth_sum + EPSILON)).tolist())
        iou_values.extend(((intersection + EPSILON) / (union + EPSILON)).tolist())
        tp += int(np.sum(predicted & truth))
        tn += int(np.sum((~predicted) & (~truth)))
        fp += int(np.sum(predicted & (~truth)))
        fn += int(np.sum((~predicted) & truth))
    metrics = {
        "mean_dice": float(np.mean(dice_values)),
        "mean_iou": float(np.mean(iou_values)),
        "pixel_sensitivity": float((tp + EPSILON) / (tp + fn + EPSILON)),
        "pixel_specificity": float((tn + EPSILON) / (tn + fp + EPSILON)),
        "tp_pixels": tp,
        "tn_pixels": tn,
        "fp_pixels": fp,
        "fn_pixels": fn,
    }
    return metrics, np.asarray(dice_values), np.asarray(iou_values)


