"""## 38. Skin-Tone Bias and Limitations

### Skin-Tone Diversity and Fairness Limitation

The ISIC datasets used here do not provide sufficiently reliable and balanced skin-tone annotations for a scientifically valid subgroup fairness analysis. This project therefore cannot honestly claim equivalent performance across skin tones. It does not invent Fitzpatrick labels, use mean image brightness as a skin-tone proxy, infer ethnicity, or artificially darken images and claim that bias has been solved.

Future work requires more diverse dermoscopic datasets, expert skin-tone annotation, subgroup sensitivity and specificity analysis, external validation, and reweighting or oversampling only when genuine subgroup labels exist.

### Other limitations

- SIIM-ISIC 2020 is highly imbalanced, even after class weighting.
- Domain shift can occur across clinics, cameras and acquisition protocols; dermoscopic images are not equivalent to ordinary smartphone photographs.
- Hair, ruler markings, gel bubbles, reflections, low contrast and lighting differences can affect segmentation and classification.
- Segmentation errors can propagate into ROI cropping and classification.
- False negatives remain possible and are particularly consequential for melanoma decision support.
- Grad-CAM is a coarse influence map, not a causal or histopathological explanation.
- Clinical use would require prospective external validation, human-factors testing, quality systems and applicable medical-device regulatory review.
"""

def evaluate_fairness_by_group(
    predictions_dataframe,
    group_column,
    target_column="target",
    probability_column="malignancy_probability",
    threshold=SELECTED_CLS_THRESHOLD,
):
    required = {group_column, target_column, probability_column}
    missing = required - set(predictions_dataframe.columns)
    if missing:
        raise ValueError(f"Missing genuine subgroup-evaluation columns: {sorted(missing)}")
    rows = []
    for group_value, group_frame in predictions_dataframe.groupby(group_column, dropna=False):
        truth = group_frame[target_column].astype(int).to_numpy()
        probability = group_frame[probability_column].astype(float).to_numpy()
        prediction = (probability >= threshold).astype(int)
        tn_g, fp_g, fn_g, tp_g = confusion_matrix(truth, prediction, labels=[0, 1]).ravel()
        rows.append({
            "group": group_value,
            "n": len(group_frame),
            "sensitivity": tp_g / (tp_g + fn_g) if tp_g + fn_g else np.nan,
            "specificity": tn_g / (tn_g + fp_g) if tn_g + fp_g else np.nan,
            "accuracy": accuracy_score(truth, prediction),
            "f1_score": f1_score(truth, prediction, zero_division=0),
            "roc_auc": roc_auc_score(truth, probability) if len(np.unique(truth)) == 2 else np.nan,
        })
    return pd.DataFrame(rows)


