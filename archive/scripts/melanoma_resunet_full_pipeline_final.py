"""## 28. EfficientNetB0

Keras EfficientNetB0 includes its own input rescaling and expects float pixel values in the 0–255 range. Therefore the `tf.data` classification decoder does **not** divide by 255 and no separate `preprocess_input` call is applied. This prevents double normalisation.
"""

def build_efficientnet_classifier(input_shape=(*CLS_IMAGE_SIZE, 3), weights="imagenet"):
    inputs = keras.Input(shape=input_shape, dtype=tf.float32, name="lesion_roi")
    backbone = keras.applications.EfficientNetB0(
        include_top=False,
        weights=weights,
        input_shape=input_shape,
    )
    backbone.trainable = False
    features = backbone(inputs, training=False)
    pooled = layers.GlobalAveragePooling2D(name="classification_gap")(features)
    dropped = layers.Dropout(0.30, name="classification_dropout")(pooled)
    outputs = layers.Dense(
        1, activation="sigmoid", dtype="float32", name="malignancy_probability"
    )(dropped)
    return keras.Model(inputs, outputs, name="EfficientNetB0_Melanoma"), backbone


