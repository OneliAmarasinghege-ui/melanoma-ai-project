def file_is_valid(path, kind):
    path = Path(path)
    if not path.exists() or path.stat().st_size < 100:
        return False

    if kind == "zip":
        return zipfile.is_zipfile(path)

    if kind == "csv":
        try:
            return len(pd.read_csv(path, nrows=3).columns) >= 1
        except Exception:
            return False

    return True


def remote_file_size(url, timeout=30):
    try:
        response = requests.head(
            url,
            allow_redirects=True,
            timeout=timeout,
        )
        response.raise_for_status()
        value = response.headers.get("Content-Length")
        return int(value) if value else None
    except Exception:
        return None


def download_with_resume(spec, destination_dir=None, chunk_mb=8):
    """
    Download one official ISIC file into temporary runtime storage.

    Large data are intentionally NOT saved to Google Drive.
    """
    destination_dir = Path(destination_dir or ARCHIVE_DIR)
    destination_dir.mkdir(parents=True, exist_ok=True)

    final_path = destination_dir / spec["filename"]
    part_path = final_path.with_suffix(final_path.suffix + ".part")

    if file_is_valid(final_path, spec["kind"]):
        print("Valid runtime file already exists; skipping:", final_path.name)
        return final_path

    remote_size = remote_file_size(spec["url"])
    start_byte = part_path.stat().st_size if part_path.exists() else 0
    headers = {"Range": f"bytes={start_byte}-"} if start_byte else {}
    mode = "ab" if start_byte else "wb"

    try:
        with requests.get(
            spec["url"],
            stream=True,
            headers=headers,
            timeout=(30, 120),
        ) as response:
            response.raise_for_status()

            if start_byte and response.status_code != 206:
                print("Server did not honour resume; restarting this file.")
                start_byte = 0
                mode = "wb"

            total = remote_size or int(
                response.headers.get("Content-Length", 0)
            ) or None

            with open(part_path, mode) as handle, tqdm(
                total=total,
                initial=start_byte,
                unit="B",
                unit_scale=True,
                desc=spec["filename"],
            ) as progress:
                for chunk in response.iter_content(
                    chunk_size=chunk_mb * 1024 * 1024
                ):
                    if chunk:
                        handle.write(chunk)
                        progress.update(len(chunk))

        part_path.replace(final_path)

        if not file_is_valid(final_path, spec["kind"]):
            raise RuntimeError(
                "Downloaded file failed its integrity check."
            )

        return final_path

    except Exception as exc:
        message = (
            f"Automatic download failed for {spec['filename']}.\n"
            f"The file was being downloaded to temporary Colab storage:\n"
            f"{final_path}\n\n"
            "You do NOT need to place the large archive in Google Drive.\n"
            f"Original error: {exc}"
        )
        print(message)
        raise RuntimeError(message) from exc


